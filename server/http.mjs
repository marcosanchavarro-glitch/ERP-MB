import {officeWorkRouter} from './office-work/http.mjs';
import {importRouter} from './imports/http.mjs';
import {appointmentsRouter} from './appointments/http.mjs';
import {readFile} from 'node:fs/promises';
import {newcomersRouter} from './newcomers/http.mjs';
import {createOfficeService} from './office/service.mjs';
import {officeRouter} from './office/http.mjs';
import {branding} from './core/branding.mjs';
import {createIdentityAdmin} from './identity/admin-service.mjs';
import {identityAdminRouter} from './identity/admin-http.mjs';
import {assertModule} from './identity/modules.mjs';
import {createFollowupService} from './followup/service.mjs';
import {followupRouter} from './followup/http.mjs';
import http from 'node:http';
import express from 'express';
import helmet from 'helmet';
import {rateLimit} from 'express-rate-limit';
import {randomUUID} from 'node:crypto';
import {resolve} from 'node:path';
import {DomainError} from './core/errors.mjs';
import {log} from './core/logger.mjs';
import {installIdentity} from './identity/http.mjs';
import {peopleRouter} from './people/http.mjs';
import {createCellsService} from './cells/service.mjs';
import {cellsRouter} from './cells/http.mjs';
import {createMeetingsService} from './meetings/service.mjs';
import {meetingsRouter} from './meetings/http.mjs';
import {createLeaderService} from './leader/service.mjs';
import {leaderRouter} from './leader/http.mjs';
const root=resolve(import.meta.dirname,'..');
export async function createAppServer(people,{pool,config}) {
 const publicIdentity=config.branding||branding({});
 const escapeHtml=value=>String(value).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
 const app=express();app.disable('x-powered-by');
 if(config.trustProxy)app.set('trust proxy',config.trustProxy);
 app.use((req,res,next)=>{
  req.requestId=randomUUID();res.setHeader('X-Request-Id',req.requestId);res.setHeader('Cache-Control','no-store');
  const start=Date.now();res.on('finish',()=>log('info','request',{requestId:req.requestId,method:req.method,route:req.route?.path || 'static-or-unmatched',status:res.statusCode,durationMs:Date.now()-start}));
  next();
 });
 app.use(helmet({contentSecurityPolicy:{directives:{defaultSrc:["'self'"],scriptSrc:["'self'"],styleSrc:["'self'","'unsafe-inline'",'https://fonts.googleapis.com'],fontSrc:["'self'",'https://fonts.gstatic.com'],imgSrc:["'self'",'data:'],connectSrc:["'self'"],frameAncestors:["'none'"],baseUri:["'none'"],formAction:["'self'"],upgradeInsecureRequests:config.production?[]:null}},referrerPolicy:{policy:'no-referrer'},strictTransportSecurity:config.production?{maxAge:31536000,includeSubDomains:true}:false}));
 app.get('/health/live',(req,res)=>res.json({status:'ok'}));
 app.get('/health/ready',async(req,res)=>{try{await pool.query('SELECT 1');res.json({status:'ok'});}catch{res.status(503).json({status:'unavailable'});}});
 app.use((req,res,next)=>{
  if(req.headers.host!==new URL(config.origin).host)return next(new DomainError(403,'Host no permitido.'));
  if(config.production&&!req.secure)return next(new DomainError(400,'Se requiere una conexión HTTPS.'));
  if(req.headers['sec-fetch-site']==='cross-site')return next(new DomainError(403,'Origen no permitido.'));
  if(!['GET','HEAD','OPTIONS'].includes(req.method)&&req.headers.origin!==config.origin)return next(new DomainError(403,'Origen no permitido.'));
  next();
 });
 app.get('/api/installation',(req,res)=>res.json(publicIdentity));
 app.use('/api',rateLimit({windowMs:60000,limit:config.apiLimit,standardHeaders:'draft-8',legacyHeaders:false,handler:(req,res,next)=>next(new DomainError(429,'Demasiadas solicitudes. Intentá nuevamente en un momento.'))}));
 app.use('/api/cells/:id/close',express.json({limit:'1mb',strict:true}));
 app.use('/api/meetings/:id/actions',express.json({limit:'4mb',strict:true}));
 app.use('/api/leader/cells/:cellId/meetings/:id/actions',express.json({limit:'4mb',strict:true}));
 app.use('/api/imports',express.json({limit:'12mb',strict:true}));
 app.use('/api',express.json({limit:'32kb',strict:true}));
 const sessionStore=await installIdentity(app,pool,config);
 app.use('/api/imports',importRouter(pool,{secret:config.sessionSecret}));
 app.use('/api/appointments',appointmentsRouter(pool,{timezone:config.timezone}));
 app.use('/api/office-work',officeWorkRouter(pool,{timezone:config.timezone}));
 app.use('/api/office',officeRouter(createOfficeService(pool,{timezone:config.timezone})));
 app.use('/api/newcomers',newcomersRouter(pool));
 app.use('/api/admin/users',identityAdminRouter(createIdentityAdmin(pool)));
 app.get('/api/modules/:id/access',(req,res)=>{const node=assertModule(req.user,req.params.id);res.json({id:node.id,path:node.path,status:node.status});});
 app.use('/api/followup',followupRouter(createFollowupService(pool)));
 app.use('/api/people',peopleRouter(people));
 app.use('/api/cells',cellsRouter(createCellsService(pool),pool));
 app.use('/api/meetings',meetingsRouter(createMeetingsService(pool)));
 app.use('/api/leader',leaderRouter(createLeaderService(pool)));
 app.use('/api',(req,res,next)=>next(new DomainError(404,'No encontramos esta operación.')));
 app.get('/',async(req,res)=>{const html=await readFile(resolve(root,'index.html'),'utf8');res.type('html').send(html.replace('{{APP_TITLE}}',()=>escapeHtml(publicIdentity.productName)).replace('{{APP_DESCRIPTION}}',()=>escapeHtml(publicIdentity.productName+' · '+publicIdentity.organizationName)));});
 app.use('/src',express.static(resolve(root,'src'),{dotfiles:'deny',index:false,etag:false,maxAge:0}));
 app.use((req,res,next)=>next(new DomainError(404,'No encontramos esta página.')));
 app.use((error,req,res,next)=>{
  const known=error instanceof DomainError;
  const status=known?error.status:error.type==='entity.too.large'?413:error.type==='entity.parse.failed'||error instanceof URIError?400:500;
  log(status>=500?'error':status===401||status===403?'security':'warn','request_error',{requestId:req.requestId,status,code:known?error.details.code || 'DOMAIN_ERROR':error.code || error.type || 'INTERNAL'});
  if(res.headersSent)return next(error);
  res.status(status).json({message:known?error.message:status===400?'No pudimos leer la solicitud.':status===413?'El formulario es demasiado extenso.':'No pudimos completar la operación. Intentá nuevamente.',...(known?error.details:{}),requestId:req.requestId});
 });
 const server=http.createServer({requestTimeout:30000,headersTimeout:15000},app);
 server.on('close',()=>sessionStore.close());return server;
}
